#!/usr/bin/env python
"""Scan the audio drop dir and list pending lessons with friendly basenames.

For each audio file in `/Users/viola/Data/Insta360/Audio/`, resolve the UTC
start (sidecar > Voice Memos DB), ffprobe duration, derive a Pacific-local
friendly basename, and flag whether the recording already has a transcript
in `Analyze/Transcripts/`. Print a table the user can scan + copy-paste a
basename into `Scripts/new_lesson.py`.

Read-only: this script never writes anything (modulo sidecar caching as a
side-effect of `_resolve_audio_start`).
"""
from __future__ import annotations

import argparse
import json
import logging
import os
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from Libraries.audio_transcribe import (
    PACIFIC_TZ,
    _format_friendly_duration,
    resolve_friendly_basename,
)
from Libraries.voice_audio import AUDIO_DROP_DIR, AUDIO_EXTS, VoiceAudioUnresolvable

LOG = logging.getLogger(__name__)

DEFAULT_TRANSCRIPTS_DIR = REPO_ROOT / "Analyze" / "Transcripts"


def _scan_audio_dir(audio_dir: str) -> list[str]:
    out = []
    for name in sorted(os.listdir(audio_dir)):
        if name.lower().endswith(AUDIO_EXTS):
            out.append(os.path.join(audio_dir, name))
    return out


def _transcribed_basenames(transcripts_dir: Path) -> set[str]:
    """Set of basenames that have a `.summary.md` next to them. We treat
    that as the canonical 'already-processed' marker — the transcript may or
    may not be present (transcripts can be regenerated by hand), but if there's
    a summary, the lesson exists.
    """
    if not transcripts_dir.is_dir():
        return set()
    out = set()
    for p in transcripts_dir.glob("*.summary.md"):
        out.add(p.stem[: -len(".summary")] if p.stem.endswith(".summary") else p.stem)
    return out


def _transcripts_by_source(transcripts_dir: Path) -> dict[str, str]:
    """Map source-audio filename → basename of the existing transcript artifact.
    Built by reading the `audio_file` header from each `<base>.transcript.*.json`.
    Catches lessons transcribed under a manually-renamed basename (e.g. the
    pre-CLI `2026-05-03_lesson` style) so we don't propose re-transcribing them
    under the now-canonical friendly basename.
    """
    out: dict[str, str] = {}
    if not transcripts_dir.is_dir():
        return out
    for p in transcripts_dir.glob("*.transcript.*.json"):
        m = re.match(r"^(.+?)\.transcript\.[^.]+\.json$", p.name)
        if not m:
            continue
        base = m.group(1)
        try:
            with open(p) as f:
                d = json.load(f)
            af = d.get("audio_file")
        except Exception:
            continue
        if af:
            out[af] = base
    return out


def _shorten_source(name: str, width: int = 50) -> str:
    if len(name) <= width:
        return name
    return name[: width - 1] + "…"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--audio-dir", default=AUDIO_DROP_DIR)
    ap.add_argument("--transcripts-dir", default=str(DEFAULT_TRANSCRIPTS_DIR))
    ap.add_argument("--all", action="store_true",
                    help="also list already-transcribed audio (default: pending only)")
    ap.add_argument("--basenames-only", action="store_true",
                    help="print only suggested basenames (one per line); useful for scripting")
    ap.add_argument("-v", "--verbose", action="store_true")
    args = ap.parse_args()

    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.WARNING,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
        datefmt="%H:%M:%S",
    )

    audio_dir = args.audio_dir
    transcripts_dir = Path(args.transcripts_dir)
    if not os.path.isdir(audio_dir):
        sys.exit(f"audio dir not found: {audio_dir}")

    done = _transcribed_basenames(transcripts_dir)
    by_source = _transcripts_by_source(transcripts_dir)

    pending = []
    transcribed = []
    failed = []

    for path in _scan_audio_dir(audio_dir):
        source_name = os.path.basename(path)
        source_base = os.path.splitext(source_name)[0]
        try:
            basename, start_utc, duration_s, source = resolve_friendly_basename(path)
        except VoiceAudioUnresolvable as e:
            failed.append((source_name, str(e).splitlines()[0]))
            continue
        except Exception as e:  # ffprobe failure, etc.
            failed.append((source_name, f"{type(e).__name__}: {e}"))
            continue

        local = start_utc.astimezone(PACIFIC_TZ)
        existing_base = by_source.get(source_name)
        row = {
            "basename": basename,
            "duration_s": duration_s,
            "duration_str": _format_friendly_duration(duration_s),
            "local_str": local.strftime("%a %Y-%m-%d %H:%M %Z"),
            "source_name": source_name,
            "source_path": path,
            "existing_basename": existing_base,
        }
        # "Already transcribed" if ANY of:
        #   - the friendly basename has a .summary.md (canonical case)
        #   - the source basename has a .summary.md (legacy, source-name as basename)
        #   - some transcript JSON's `audio_file` header references this source
        #     (manually-renamed lessons, e.g. `2026-05-03_lesson` from before
        #      friendly basenames existed)
        if basename in done or source_base in done or existing_base is not None:
            transcribed.append(row)
        else:
            pending.append(row)

    if args.basenames_only:
        for r in pending:
            print(r["basename"])
        return

    print(f"Audio dir: {audio_dir}")
    print(f"Transcripts dir: {transcripts_dir}")
    print(f"  {len(pending)} pending, {len(transcribed)} transcribed, "
          f"{len(failed)} unresolvable")
    print()

    if pending:
        print(f"Pending ({len(pending)}):")
        _print_table(pending)
    else:
        print("Pending: (none)")
    print()

    if failed:
        print(f"Unresolvable ({len(failed)}):")
        for name, why in failed:
            print(f"  {name}\n    {why}")
        print()

    if args.all and transcribed:
        print(f"Already transcribed ({len(transcribed)}):")
        _print_table(transcribed, show_existing=True)
        print()

    if pending:
        first = pending[0]["basename"]
        print(f"Next step (example):")
        print(f"  conda run --no-capture-output -n sailing python "
              f"Scripts/new_lesson.py '{first}'")


def _print_table(rows: list[dict], show_existing: bool = False) -> None:
    name_w = max((len(r["basename"]) for r in rows), default=0)
    dur_w = max((len(r["duration_str"]) for r in rows), default=0)
    local_w = max((len(r["local_str"]) for r in rows), default=0)
    name_w = max(name_w, len("basename"))
    dur_w = max(dur_w, len("dur"))
    local_w = max(local_w, len("start (Pacific)"))
    header = f"  {'basename':<{name_w}}  {'dur':<{dur_w}}  {'start (Pacific)':<{local_w}}  source"
    sep = f"  {'-' * name_w}  {'-' * dur_w}  {'-' * local_w}  {'-' * 6}"
    if show_existing:
        header += "   [existing artifact]"
    print(header)
    print(sep)
    for r in rows:
        line = (f"  {r['basename']:<{name_w}}  {r['duration_str']:<{dur_w}}  "
                f"{r['local_str']:<{local_w}}  {_shorten_source(r['source_name'])}")
        if show_existing and r.get("existing_basename"):
            line += f"   -> {r['existing_basename']}"
        print(line)


if __name__ == "__main__":
    main()
