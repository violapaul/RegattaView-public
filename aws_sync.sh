#!/bin/bash

# fail on an error and be verbose
set -evu

BASE="/Users/viola/www"
S3="s3://regattaanalysis"
AWS_PROFILE="${AWS_PROFILE:-regatta}"
export AWS_PROFILE
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# CloudFront distribution that fronts the regattaanalysis bucket. Same
# default as Scripts/race_upload.py and Scripts/aws_egress_killswitch.sh.
CF_DIST_ID="${CF_DIST_ID:-EPCTF7XCNPLK2}"

################################################################
# Stage generated review data
#
# review.html and tracks.html read only these generated artifacts under
# www/Analyze: events_index.json, Events/, Sessions/, optional AIS/, and
# AISDays/. Keep the staged tree minimal so scripts, tests, plots, and local
# edits never leak into S3.
ANALYZE_SRC="$REPO_ROOT/Analyze"
ANALYZE_STAGE="$BASE/Analyze"
if [ -f "$ANALYZE_SRC/events_index.json" ]; then
    ANALYZE_STAGE_TMP="${ANALYZE_STAGE}.tmp"
    rm -rf "$ANALYZE_STAGE_TMP"
    mkdir -p "$ANALYZE_STAGE_TMP"
    rsync -a "$ANALYZE_SRC/events_index.json" "$ANALYZE_STAGE_TMP/"
    for dir in Events Sessions AIS AISDays Transcripts Notes; do
        if [ -d "$ANALYZE_SRC/$dir" ]; then
            mkdir -p "$ANALYZE_STAGE_TMP/$dir"
            # Exclude per-note generator scripts (Notes/<slug>/scripts/) — analysis
            # code, not web content; a note ships as note.html + figures only.
            rsync -a --exclude 'scripts/' "$ANALYZE_SRC/$dir/" "$ANALYZE_STAGE_TMP/$dir/"
        fi
    done
    rm -rf "$ANALYZE_STAGE"
    mv "$ANALYZE_STAGE_TMP" "$ANALYZE_STAGE"
else
    echo "WARNING: $ANALYZE_SRC/events_index.json not found; leaving staged Analyze/ unchanged"
fi

################################################################
# Sync the remaining files
cd "$BASE"

# `no-cache` = browser caches the response but MUST revalidate with S3
# (via If-None-Match) before serving it. 304 hits are tiny; the win is
# that users (especially iOS PWAs with no URL bar to cache-bust) see new
# builds on the next launch instead of sticking on an old version for
# hours due to S3's lack of a default Cache-Control and Safari's
# heuristic caching. Webpack output is not content-hashed, so there is
# no safe long-lived alternative for the JS/CSS packs.
aws s3 sync sailview "$S3/www/sailview" \
    --cache-control "no-cache, must-revalidate"

# Analyze/ holds events_index.json + Events/ + Sessions/ (generated by
# race_upload.py --analyze). Drives review.html. We do NOT sync Comments/
# here — those files are client-write-only (S3 is the source of truth and
# a local stale copy would clobber live user comments).
#
# Short max-age (60 s) so a freshly-pushed events_index.json surfaces at
# the CloudFront edge within a minute even if the explicit invalidation
# below fails or the operator forgets it.
aws s3 sync Analyze "$S3/www/Analyze" \
    --cache-control "public, max-age=60" \
    --exclude "events_edits.json" \
    --exclude "Comments/*"

# Big binary mirrors. Write-once-keyed-by-name in steady state; long TTL
# is correct here. Rewrites land via race_upload.py which issues a
# surgical per-file CloudFront invalidation. The rare hand-edited rewrite
# under one of these dirs needs a manual `aws cloudfront create-invalidation`
# (or wait up to a week for the edge to expire).
for i in FullLogs SeattleTiles; do
    echo "$i"
    aws s3 sync "$i" "$S3/www/$i" \
        --cache-control "public, max-age=604800"
done

# Punch the CloudFront edge cache for the small JSON metadata under
# Analyze/. `aws s3 sync` doesn't tell us per-file what changed in a
# machine-readable way, so we wildcard-invalidate the whole tree — these
# files are tiny (kilobytes) and re-population from S3 is cheap. Counts as
# one billable invalidation request spanning two paths; CF gives 1000
# free per month.
aws cloudfront create-invalidation \
    --distribution-id "$CF_DIST_ID" \
    --paths "/www/Analyze/*" "/www/sailview/*"
